// "auto": tháng 12 → Noel; 20/1–20/2 → Tết (gần đúng — Tết âm lịch đổi ngày mỗi năm; chọn tay nếu lệch).
export function resolveSeason(id, now = new Date()) {
  if (id !== "auto") return id;
  const m = now.getMonth() + 1;
  const d = now.getDate();
  if (m === 12) return "noel";
  if ((m === 1 && d >= 20) || (m === 2 && d <= 20)) return "tet";
  return "off";
}

export function themeById(id) {
  return THEMES.find((t) => t.id === id) || THEMES[0];
}
